const DISTINCT_INDONESIAN_WORDS = [...new Set(INDONESIAN_WORD_CANDIDATES)];
const REQUIRED_INDONESIAN_WORDS = [
    'ada',
    'bahasa',
    'belajar',
    'indonesia',
    'kata',
    'komputer',
    'mengetik',
    'rumah',
    'yang',
] as const;

const selectEvenDistribution = (
    words: readonly string[],
    count: number,
): readonly string[] =>
    words.filter(
        (_, index) =>
            Math.floor(((index + 1) * count) / words.length) >
            Math.floor((index * count) / words.length),
    );

export const INDONESIAN_WORDS: readonly string[] = Object.freeze([
    ...REQUIRED_INDONESIAN_WORDS,
    ...selectEvenDistribution(
        DISTINCT_INDONESIAN_WORDS.filter(
            (word) =>
                !REQUIRED_INDONESIAN_WORDS.some(
                    (required) => required === word,
                ),
        ),
        520 - REQUIRED_INDONESIAN_WORDS.length,
    ),
]);
